#!/usr/bin/env python3
"""Rebuild MRSS vector icon resources and the editable SVG from one geometry."""
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "android/app/src/main/res"
ANDROID = "http://schemas.android.com/apk/res/android"
AAPT = "http://schemas.android.com/aapt"
ET.register_namespace("android", ANDROID)
ET.register_namespace("aapt", AAPT)


def rounded(x, y, width, height, radius):
    return (f"M{x+radius},{y} H{x+width-radius} Q{x+width},{y} {x+width},{y+radius} "
            f"V{y+height-radius} Q{x+width},{y+height} {x+width-radius},{y+height} "
            f"H{x+radius} Q{x},{y+height} {x},{y+height-radius} "
            f"V{y+radius} Q{x},{y} {x+radius},{y} Z")


def circle(x, y, radius):
    return f"M{x-radius},{y} a{radius},{radius} 0,1 0 {2*radius},0 a{radius},{radius} 0,1 0 {-2*radius},0"


# Foreground bounds stay inside the central 66dp safe area of a 108dp layer.
BODY = rounded(23, 32, 62, 44, 12)
SCREEN = rounded(47, 37, 32, 34, 7)
ARROWS = "M54,48 H72 M67,43 L72,48 L67,53 M72,60 H54 M59,55 L54,60 L59,65"
GRADIENTS = {
    "blue": (14, 0, 91, 108, [(0, "#69ADFF"), (.48, "#387FF0"), (1, "#2455D6")]),
    "glass": (31, 32, 75, 79, [(0, "#FFFFFF"), (.45, "#F2F8FF"), (1, "#C9DFFF")]),
    "screen": (50, 37, 76, 74, [(0, "#6FAFFF"), (.48, "#3D86F2"), (1, "#245DDC")]),
    "lens": (31, 40, 40, 67, [(0, "#375478"), (1, "#142C50")]),
}
BACKGROUND = [
    dict(d="M0,0 H108 V108 H0 Z", fill="blue"),
    dict(d="M0,0 H108 V19 C75,6 33,43 0,30 Z", fill="#FFFFFF", opacity=.07),
]
FOREGROUND = [
    dict(d=rounded(23, 34, 62, 44, 12), fill="#143D9F", opacity=.16),
    dict(d=BODY, fill="glass", stroke="#FFFFFF", stroke_opacity=.75, width=.7),
    dict(d=circle(35.5, 45.5, 6.5)+circle(35.5, 62.5, 6.5), fill="#B8D0ED"),
    dict(d=circle(35.5, 45.5, 5.2)+circle(35.5, 62.5, 5.2), fill="lens"),
    dict(d=circle(34.1, 44, 1.65)+circle(34.1, 61, 1.65), fill="#A3CDFF", opacity=.65),
    dict(d=SCREEN, fill="screen", stroke="#FFFFFF", stroke_opacity=.5, width=.6),
    dict(d="M54,37 H72 Q79,37 79,44 V46 C66,42 60,52 47,49 V44 Q47,37 54,37 Z", fill="#FFFFFF", opacity=.12),
    dict(d=ARROWS, stroke="#FFFFFF", width=2.7),
]
MONOCHROME = [
    dict(d=BODY, stroke="#FFFFFF", width=3.4),
    dict(d=circle(35.5, 45.5, 5.3)+circle(35.5, 62.5, 5.3), fill="#FFFFFF"),
    dict(d=ARROWS, stroke="#FFFFFF", width=3.4),
]


def android_attrs(**attrs):
    return {f"{{{ANDROID}}}{key}": str(value) for key, value in attrs.items()}


def vector(size=108):
    return ET.Element("vector", android_attrs(width=f"{size}dp", height=f"{size}dp", viewportWidth=size, viewportHeight=size))


def add_paths(parent, paths):
    for spec in paths:
        fill = spec.get("fill", "#00000000")
        attrs = android_attrs(pathData=spec["d"])
        if fill not in GRADIENTS:
            attrs.update(android_attrs(fillColor=fill))
        if "opacity" in spec:
            attrs.update(android_attrs(fillAlpha=spec["opacity"]))
        if "stroke" in spec:
            attrs.update(android_attrs(strokeColor=spec["stroke"], strokeWidth=spec["width"],
                                       strokeLineCap="round", strokeLineJoin="round",
                                       strokeAlpha=spec.get("stroke_opacity", 1)))
        path = ET.SubElement(parent, "path", attrs)
        if fill in GRADIENTS:
            x1, y1, x2, y2, stops = GRADIENTS[fill]
            item = ET.SubElement(path, f"{{{AAPT}}}attr", {"name": "android:fillColor"})
            gradient = ET.SubElement(item, "gradient", android_attrs(type="linear", startX=x1, startY=y1, endX=x2, endY=y2))
            for offset, color in stops:
                ET.SubElement(gradient, "item", android_attrs(offset=offset, color=color))


def save_xml(relative, element):
    path = RES / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    ET.indent(element, space="    ")
    path.write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/generate_launcher_icons.py. -->\n'
                    + ET.tostring(element, encoding="unicode") + "\n")


def main():
    for name, paths in [("background", BACKGROUND), ("foreground", FOREGROUND), ("monochrome", MONOCHROME)]:
        icon = vector()
        add_paths(icon, paths)
        save_xml(f"drawable/ic_launcher_{name}.xml", icon)

    # A standalone rounded tile for About and Android 7; adaptive layers have no outer mask.
    logo = vector()
    group = ET.SubElement(logo, "group")
    ET.SubElement(group, "clip-path", android_attrs(pathData=rounded(2, 2, 104, 104, 26)))
    add_paths(group, BACKGROUND)
    mark = ET.SubElement(group, "group", android_attrs(pivotX=54, pivotY=54, scaleX=1.32, scaleY=1.32))
    add_paths(mark, FOREGROUND)
    save_xml("drawable/ic_app_logo.xml", logo)

    status = vector(24)
    mark = ET.SubElement(status, "group", android_attrs(scaleX=1/3, scaleY=1/3, translateX=-6, translateY=-6))
    add_paths(mark, MONOCHROME)
    save_xml("drawable/ic_stat_mrss.xml", status)

    adaptive = ET.Element("adaptive-icon")
    for name in ["background", "foreground", "monochrome"]:
        ET.SubElement(adaptive, name, android_attrs(drawable=f"@drawable/ic_launcher_{name}"))
    save_xml("mipmap-anydpi-v26/ic_launcher.xml", adaptive)
    save_xml("mipmap-anydpi/ic_launcher.xml", ET.Element("inset", android_attrs(drawable="@drawable/ic_app_logo", inset="0dp")))

    # Editable, framework-independent version of the same mark, no image tooling required.
    svg = ET.Element("svg", {"xmlns": "http://www.w3.org/2000/svg", "viewBox": "0 0 108 108", "width": "512", "height": "512"})
    defs = ET.SubElement(svg, "defs")
    for name, (x1, y1, x2, y2, stops) in GRADIENTS.items():
        gradient = ET.SubElement(defs, "linearGradient", {"id": name, "gradientUnits": "userSpaceOnUse", "x1": str(x1), "y1": str(y1), "x2": str(x2), "y2": str(y2)})
        for offset, color in stops:
            ET.SubElement(gradient, "stop", {"offset": str(offset), "stop-color": color})
    clip = ET.SubElement(defs, "clipPath", {"id": "tile"})
    ET.SubElement(clip, "path", {"d": rounded(2, 2, 104, 104, 26)})
    tile = ET.SubElement(svg, "g", {"clip-path": "url(#tile)"})
    for paths in [BACKGROUND, FOREGROUND]:
        parent = tile if paths is BACKGROUND else ET.SubElement(tile, "g", {"transform": "translate(54 54) scale(1.32) translate(-54 -54)"})
        for spec in paths:
            attrs = {"d": spec["d"], "fill": f'url(#{spec["fill"]})' if spec.get("fill") in GRADIENTS else spec.get("fill", "none")}
            if "opacity" in spec:
                attrs["fill-opacity"] = str(spec["opacity"])
            if "stroke" in spec:
                attrs.update({"stroke": spec["stroke"], "stroke-width": str(spec["width"]), "stroke-opacity": str(spec.get("stroke_opacity", 1)), "stroke-linecap": "round", "stroke-linejoin": "round"})
            ET.SubElement(parent, "path", attrs)
    ET.indent(svg, space="  ")
    (ROOT / "pic_res/app-icon.svg").write_text(ET.tostring(svg, encoding="unicode") + "\n")


if __name__ == "__main__":
    main()
